"""导入结果文案（3.7.39 从 services/inbox.py 拆出）。

为什么单独成模块：拆分时 inbox.py 已顶到当时的 600 行上限（现标准 800/400），
而"同名洗版"提示是纯文案逻辑、与落盘无关；
搬出来既过闸门，也让导入管线只关心"做什么"。

背景（用户报障）：替换洗版不会让社团在「最近入库」排序里上浮——`_group_arrival` 的判据是
作品数量增加。旧日志只写"已导入"，用户不知道自己刚做的是洗版，于是误以为排序坏了。
"""
import os


def dup_name_hint(dest, exact):
    """同名目标已存在时的日志提示。

    exact=True：压缩包已经过内容哈希比对，可断定"内容不同"（同内容会走"重复内容"分支）；
    exact=False：文件夹/散图无法整体比对，只说"同名"，不断言内容。
    """
    why = "、内容不同" if exact else ""
    return ("⚠ 库里已有同名作品%s：已另存为「%s」，原文件未动。"
            "这是替换洗版，不会让社团在「最近入库」排序里上浮"
            "（要按文件时间排请切到「最近更新」档）" % (why, os.path.basename(dest)))
